import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));

/** Only the canonical, already-public resume is a build input. Never scan private/. */
export async function generateKnowledge(
  resumePath = path.join(root, 'readme.md'),
  outputPath = path.join(root, 'apps/api/src/knowledge.generated.ts'),
) {
  const resume = await readFile(resumePath, 'utf8');
  if (!resume.trim() || Buffer.byteLength(resume) > 64 * 1024) {
    throw new Error('Public resume must be nonempty and at most 64 KiB.');
  }
  const version = createHash('sha256').update(resume).digest('hex').slice(0, 16);
  const module = [
    '// Generated by scripts/generate-chat-knowledge.mjs from readme.md. Do not edit.',
    `export const RESUME_TEXT = ${JSON.stringify(resume)};`,
    `export const RESUME_VERSION = ${JSON.stringify(version)};`,
    '',
  ].join('\n');
  await mkdir(path.dirname(outputPath), { recursive: true });
  let existing;
  try {
    existing = await readFile(outputPath, 'utf8');
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  // Avoid restarting tsx watch when tests/builds regenerate unchanged knowledge.
  if (existing !== module) await writeFile(outputPath, module);
  return version;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await generateKnowledge();
}
